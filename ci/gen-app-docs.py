#!/usr/bin/env python3
"""Generate the app-testing documentation from the catalog and the test tree.

docs/apps/testing.md is generated, never hand-written: hand-written coverage docs
drift from the tests, which is exactly what the old free-text `verify.checks` list
did. This reads `umkim-thin catalog verify --json` (which resolves every check
against a real test tag) plus the catalog's human-verification logs.

Usage:
    ci/gen-app-docs.py            # write docs/apps/testing.md
    ci/gen-app-docs.py --check    # exit 1 if the committed file is out of date

--check runs from ci/static.sh, so a catalog change that is not reflected in the
docs fails the gate rather than leaving the docs lying.
"""
import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path("docs/apps/testing.md")

HEADER = """# App testing status

<!-- Generated by ci/gen-app-docs.py from the catalog and the Playwright suites.
     Do not edit by hand: run `./ci/gen-app-docs.py` (ci/static.sh checks it). -->

Every catalogued app carries two independent statements:

* **Auto-tested** - each check the entry declares is carried by a test that runs
  in the gate, so a regression fails CI without a human. *Auto-checked* means a
  test exists but it is informational (excluded from the gate).
* **Human** - the last time a person actually used the app, and on which chart
  version. When the chart has moved since, it is shown as **stale**: the check
  happened, but not on the version you are installing.

Both are derived from evidence, not typed in. A check name must appear as an
`@check:<name>` tag on a real test, which `umkim-thin catalog verify --strict`
resolves; an entry that names a check nothing carries fails the static gate.

## Summary

"""


def rows():
    out = subprocess.run(
        ["go", "run", "./cmd/umkim-thin", "catalog", "verify", "--json"],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def main() -> int:
    want_check = "--check" in sys.argv[1:]
    try:
        data = rows()
    except subprocess.CalledProcessError as exc:
        print(f"catalog verify failed: {exc.stderr}", file=sys.stderr)
        return 1

    lines = [HEADER]
    lines.append("| App | Auto | Chart | Human |")
    lines.append("|---|---|---|---|")
    for e in data:
        human = "-"
        if e.get("human"):
            h = e["human"]
            human = f"{h['date']} ({h['by']})"
            if h.get("version") and h["version"] != e["chartVersion"]:
                human += f" **stale** - verified on {h['version']}"
        lines.append(f"| {e['name']} | {e['category']} | {e['chartVersion']} | {human} |")

    lines.append("")
    lines.append("## What each check exercises")
    lines.append("")
    for e in data:
        lines.append(f"### {e['name']}")
        lines.append("")
        if e.get("checks"):
            for c in e["checks"]:
                suite = c.get("suite") or "**unresolved**"
                lines.append(f"- `{c['check']}` - {suite}")
        lines.append("")
        h = e.get("human")
        if h:
            lines.append(
                f"Human pass {h['date']} by {h['by']} on chart {h['version']}"
                f" ({', '.join(h.get('targets') or [])}):"
            )
            lines.append("")
            for step in h.get("did") or []:
                lines.append(f"- {step}")
        else:
            lines.append("No human pass is recorded for this app.")
        lines.append("")

    text = "\n".join(lines).rstrip("\n") + "\n"

    if want_check:
        existing = OUT.read_text() if OUT.exists() else ""
        if existing != text:
            print(f"{OUT} is out of date; run ./ci/gen-app-docs.py", file=sys.stderr)
            return 1
        print("   ok")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(data)} apps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
